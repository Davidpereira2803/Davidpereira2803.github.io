import { chromium } from "playwright";
import { mkdir } from "node:fs/promises";
import assert from "node:assert/strict";
await mkdir(".review", {recursive:true});
const browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:"reduce"});
const errors=[];
page.on("pageerror",e=>errors.push(e.message));
await page.goto("http://localhost:4173",{waitUntil:"networkidle"});
await page.getByRole("heading",{name:"Curiosity, put to work."}).waitFor();
assert.equal(await page.locator('a[href^="mailto:"]').count(),0);
await page.locator("#roll-control").fill("25");
await page.locator(".scope-readouts").getByText("+25°",{exact:true}).waitFor();
await page.getByRole("button",{name:"Perception",exact:true}).click();
await page.getByText("Camera → world model",{exact:true}).waitFor();
await page.getByRole("button",{name:"Reset",exact:true}).click();
assert.equal(await page.locator("#roll-control").inputValue(),"0");
await page.getByRole("button",{name:"AI/ML",exact:true}).click();
assert.equal(await page.locator(".experiment-row").count(),3);
await page.getByRole("button",{name:/FireDrift/}).click();
await page.locator(".experiment-preview h3").getByText("FireDrift",{exact:true}).waitFor();
await page.getByRole("tab",{name:"Build",exact:true}).click();
await page.getByRole("tabpanel").getByText(/ResNet18/).waitFor();
await page.getByRole("tab",{name:"Results",exact:true}).focus();
await page.keyboard.press("ArrowLeft");
assert.equal(await page.getByRole("tab",{name:"Build",exact:true}).getAttribute("aria-selected"),"true");
await page.getByRole("searchbox",{name:"Search projects"}).fill("no-project-with-this-name");
await page.getByText("No experiments match that search.").waitFor();
await page.getByRole("button",{name:"Clear filters",exact:true}).click();
assert.equal(await page.locator(".experiment-row").count(),11);
await page.getByRole("button",{name:/Observability/}).click();
await page.getByRole("heading",{name:"Look beneath the surface."}).waitFor();
await page.screenshot({path:".review/desktop-full.png",fullPage:true});
await page.goto("http://localhost:4173/projects/ros-monitor/",{waitUntil:"networkidle"});
assert.match(await page.title(),/ROS Monitor/);
await page.getByRole("tab",{name:"Build",exact:true}).click();
await page.getByRole("heading",{name:"My contribution",exact:true}).waitFor();
assert.equal(await page.getByRole("link",{name:/Source code/}).getAttribute("href"),"https://github.com/Davidpereira2803/rosground");
await page.getByRole("tab",{name:"Gallery",exact:true}).click();
assert.equal(await page.locator(".case-gallery img").count(),3);
await page.screenshot({path:".review/case-study.png",fullPage:true});
await page.getByRole("link",{name:"Connect",exact:true}).click();
await page.waitForURL("**/#contact");
await page.setViewportSize({width:390,height:844});
await page.goto("http://localhost:4173/",{waitUntil:"networkidle"});
await page.getByRole("button",{name:"Open navigation",exact:true}).click();
await page.getByRole("link",{name:"Projects",exact:true}).click();
assert.equal(await page.getByRole("button",{name:"Open navigation",exact:true}).getAttribute("aria-expanded"),"false");
await page.getByRole("button",{name:"AI/ML",exact:true}).click();
await page.screenshot({path:".review/mobile-projects.png",fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
assert.equal(overflow,false,"Mobile layout must not overflow horizontally");
await page.goto("http://localhost:4173/",{waitUntil:"networkidle"});
await page.screenshot({path:".review/mobile-hero.png",fullPage:false});
assert.deepEqual(errors,[],"No uncaught browser errors");
await browser.close();
console.log("Workstation checks passed: controls, filters, tabs, search, homelab, case study, contact, mobile navigation, overflow, and privacy.");
